A = float(input("A nuqtani kiriting: "))
B = float(input("B nuqtani kiriting: "))
C = float(input("C nuqtani kiriting: "))


AC = abs(A - C)
BC = abs(B - C)

ko_paytma = AC * BC

print(f"AC kesma uzunligi: {AC}")
print(f"BC kesma uzunligi: {BC}")
print(f"Kesmalar uzunliklarining ko'paytmasi: {ko_paytma}")
